/// Compresses an SF2 SoundFont to SF3 (its samples to Ogg Vorbis, by ffmpeg),
/// then checks the result: decompressed again, each sample has its frames
/// and its loop points back.
///
/// ```sh
/// dart run tool/compress_sound_font.dart GeneralUser-GS.sf2 GeneralUser-GS.sf3
/// dart run tool/compress_sound_font.dart in.sf2 out.sf3 --quality 5
/// dart run tool/compress_sound_font.dart --tiny lib/src/tiny_sf3.dart
/// ```
///
/// `--tiny` compresses the tiny test SoundFont into a Dart file (the
/// fixture of the tests and of the apps' tests,
/// `midiTinySoundFontSf3Bytes()`).
library;

import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:args/args.dart';
import 'package:milomedy_midi_synth_sf2/midi_synth_sf2.dart';
import 'package:milomedy_sound_fonts/sf3_ffmpeg.dart';
import 'package:milomedy_sound_fonts/sound_fonts.dart';
import 'package:process_run/shell.dart';

Future<void> main(List<String> arguments) async {
  var parser = ArgParser()
    ..addOption('quality', defaultsTo: '4', help: 'ffmpeg -q:a, -1 to 10.')
    ..addFlag('tiny', help: 'Compress the tiny test SoundFont.');
  var result = parser.parse(arguments);
  var paths = result.rest;
  var tiny = result.flag('tiny');
  if (paths.length != (tiny ? 1 : 2)) {
    stderr.writeln(
      'usage: compress_sound_font.dart <in.sf2> <out.sf3> [--quality 4]\n'
      '       compress_sound_font.dart --tiny <out.sf3>\n${parser.usage}',
    );
    exitCode = 64;
    return;
  }
  var sf2 = tiny
      ? midiTinySoundFontBytes()
      : Uint8List.fromList(await File(paths.first).readAsBytes());
  var output = File(paths.last);
  var quality = double.parse(result.option('quality')!);
  var watch = Stopwatch()..start();
  var sf3 = await midiSoundFontCompress(
    sf2,
    encode: midiFfmpegVorbisEncoder(quality: quality),
    onProgress: (done, total) {
      if (done % 50 == 0 || done == total) {
        stdout.writeln('$done / $total samples');
      }
    },
  );
  await output.parent.create(recursive: true);
  if (tiny) {
    await output.writeAsString(_tinyDart(sf3));
    await Shell(
      verbose: false,
    ).run('dart format ${shellArgument(output.path)}');
  } else {
    await output.writeAsBytes(sf3);
  }
  stdout.writeln(
    '${output.path}: ${sf3.length} bytes (${sf2.length} as SF2), '
    'in ${watch.elapsed.inSeconds} s',
  );

  // Back to SF2: the same samples, frames and loops.
  watch.reset();
  var back = await midiSoundFontDecompress(sf3);
  stdout.writeln('decompressed in ${watch.elapsedMilliseconds} ms');
  var problems = midiSoundFontSampleDifferences(sf2, back);
  for (var problem in problems.take(20)) {
    stdout.writeln(problem);
  }
  var soundFont = MidiSoundFont.fromBytes(back);
  stdout.writeln(
    '${soundFont.name}: ${soundFont.presets.length} presets, '
    '${problems.length} sample differences',
  );
  // What the compression lost: the signal to noise ratio of the samples.
  var snrs = midiSoundFontSampleSnr(sf2, back).where((snr) => snr > 0).toList()
    ..sort();
  if (snrs.isNotEmpty) {
    String at(double q) =>
        snrs[(q * (snrs.length - 1)).round()].toStringAsFixed(1);
    stdout.writeln(
      'SNR (dB) of ${snrs.length} samples: lowest ${at(0)}, 10 % ${at(.1)}, '
      'median ${at(.5)}, highest ${at(1)}',
    );
  }
  if (problems.isNotEmpty) {
    exitCode = 1;
  }
}

/// The Dart file of the tiny SF3 [bytes].
String _tinyDart(Uint8List bytes) {
  var text = base64.encode(bytes);
  var lines = [
    for (var i = 0; i < text.length; i += 72)
      "  '${text.substring(i, i + 72 > text.length ? text.length : i + 72)}'",
  ];
  return '''
// Generated by `dart run tool/compress_sound_font.dart --tiny
// lib/src/tiny_sf3.dart`, do not edit.
import 'dart:convert';
import 'dart:typed_data';

/// The tiny test SoundFont of `midiTinySoundFontBytes()` in SF3 (its two
/// samples in Ogg Vorbis by ffmpeg's libvorbis, quality 4): for the tests.
Uint8List midiTinySoundFontSf3Bytes() => base64.decode(_base64);

const _base64 =
${lines.join('\n')};
''';
}
