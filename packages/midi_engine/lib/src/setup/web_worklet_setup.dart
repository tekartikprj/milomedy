/// Builds the AudioWorklet module of an app from Dart, as
/// sqflite_common_ffi_web builds its shared worker: compiled with dart2js in
/// `.dart_tool/milomedy_midi_engine/web_worklet/`, built again only when the
/// package version, its sources, the web package or the Dart SDK change,
/// and copied next to the app's page.
library;

import 'dart:convert';
import 'dart:io';

import '../worklet_js.dart';

const _package = 'milomedy_midi_engine';

/// The packages whose sources make the worklet.
const _sourcePackages = [_package, 'milomedy_midi_synth'];

/// What [setupMidiWebWorklet] did.
class MidiWebWorkletSetupResult {
  /// The module written.
  final File file;

  /// The version of milomedy_midi_engine.
  final String version;

  /// True when compiled, false when the cached build was up to date.
  final bool built;

  /// A result.
  MidiWebWorkletSetupResult(this.file, this.version, {required this.built});
}

/// Builds the worklet module of the app at [path] (the current directory by
/// default) when needed, and writes it as [filename] in its [dir] (`web`):
/// the page loads it with `MidiWorkletPlayer.create`. [force] builds again
/// whatever the cache says.
Future<MidiWebWorkletSetupResult> setupMidiWebWorklet({
  String? path,
  String dir = 'web',
  String filename = midiWorkletDefaultUrl,
  bool force = false,
  bool verbose = false,
}) async {
  void log(String message) {
    if (verbose) {
      stdout.writeln(message);
    }
  }

  var root = Directory(path ?? '.').absolute.uri;
  var config = _packageConfig(root);
  var packages = _packageRoots(config);
  var enginePath = packages[_package];
  if (enginePath == null) {
    throw StateError(
      '$_package is not in ${config.path}: add it, then run dart pub get',
    );
  }
  var version = _pubspecVersion(enginePath);
  var key = {
    'version': version,
    'sources': _sourceHash([
      for (var name in _sourcePackages)
        if (packages[name] != null) packages[name]!,
    ]),
    'web': packages['web']?.toString(),
    'sdk': Platform.version,
  };
  var work = Directory.fromUri(
    root.resolve('.dart_tool/$_package/web_worklet/'),
  );
  var module = File.fromUri(work.uri.resolve(filename));
  var metaFile = File.fromUri(work.uri.resolve('meta.json'));
  var meta = jsonEncode(key);
  var upToDate =
      !force &&
      module.existsSync() &&
      metaFile.existsSync() &&
      metaFile.readAsStringSync() == meta;
  if (upToDate) {
    log('$filename up to date ($key)');
  } else {
    log('building $filename ($key)');
    var stopwatch = Stopwatch()..start();
    await work.create(recursive: true);
    var entry = File.fromUri(work.uri.resolve('midi_worklet_main.dart'));
    await entry.writeAsString('''
// Generated by $_package setup_web_worklet, do not edit.
import 'package:$_package/web_worklet_processor.dart';

void main() => midiWorkletMain();
''');
    var compiled = File.fromUri(work.uri.resolve('midi_worklet.dart.js'));
    var result = await Process.run(Platform.resolvedExecutable, [
      'compile',
      'js',
      '-O2',
      '--no-source-maps',
      '--packages=${config.path}',
      '-o',
      compiled.path,
      entry.path,
    ]);
    if (result.exitCode != 0) {
      throw ProcessException(
        Platform.resolvedExecutable,
        ['compile', 'js', entry.path],
        '${result.stdout}${result.stderr}',
        result.exitCode,
      );
    }
    // The dart2js output is the module: the processor registers itself.
    await module.writeAsString(
      midiWorkletModule(await compiled.readAsString(), version: version),
    );
    await metaFile.writeAsString(meta);
    stdout.writeln(
      'built $filename ($_package $version) in '
      '${stopwatch.elapsedMilliseconds} ms',
    );
  }
  var target = File.fromUri(root.resolve('$dir/$filename'));
  var content = await module.readAsBytes();
  if (!target.existsSync() ||
      !_sameBytes(await target.readAsBytes(), content)) {
    await target.parent.create(recursive: true);
    await target.writeAsBytes(content);
    stdout.writeln('wrote ${target.path}');
  }
  return MidiWebWorkletSetupResult(target, version, built: !upToDate);
}

/// The package config of [root]: in it, or in the folder of its workspace.
File _packageConfig(Uri root) {
  var directory = Directory.fromUri(root);
  while (true) {
    var file = File.fromUri(
      directory.uri.resolve('.dart_tool/package_config.json'),
    );
    if (file.existsSync()) {
      return file;
    }
    var parent = directory.parent;
    if (parent.path == directory.path) {
      throw StateError('no .dart_tool/package_config.json: run dart pub get');
    }
    directory = parent;
  }
}

/// The root folder of each package of [config].
Map<String, Uri> _packageRoots(File config) {
  var json = jsonDecode(config.readAsStringSync()) as Map;
  return {
    for (var package in (json['packages'] as List).cast<Map>())
      package['name'] as String: _folder(
        config.uri.resolve(package['rootUri'] as String),
      ),
  };
}

Uri _folder(Uri uri) => uri.path.endsWith('/') ? uri : Uri.parse('$uri/');

String _pubspecVersion(Uri package) {
  var pubspec = File.fromUri(package.resolve('pubspec.yaml'));
  var match = RegExp(
    r'^version:\s*(\S+)',
    multiLine: true,
  ).firstMatch(pubspec.readAsStringSync());
  return match?.group(1) ?? 'unknown';
}

/// A hash (FNV-1a, 32 bits) of the paths and bytes of the files in the `lib`
/// folder of [packages].
String _sourceHash(List<Uri> packages) {
  var hash = 0x811c9dc5;
  void add(List<int> bytes) {
    for (var byte in bytes) {
      hash = ((hash ^ byte) * 0x01000193) & 0xffffffff;
    }
  }

  for (var package in packages) {
    var lib = Directory.fromUri(package.resolve('lib/'));
    if (!lib.existsSync()) {
      continue;
    }
    var files = lib.listSync(recursive: true).whereType<File>().toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    for (var file in files) {
      add(utf8.encode(file.path.substring(lib.path.length)));
      add(file.readAsBytesSync());
    }
  }
  return hash.toRadixString(16).padLeft(8, '0');
}

bool _sameBytes(List<int> a, List<int> b) {
  if (a.length != b.length) {
    return false;
  }
  for (var i = 0; i < a.length; i++) {
    if (a[i] != b[i]) {
      return false;
    }
  }
  return true;
}
