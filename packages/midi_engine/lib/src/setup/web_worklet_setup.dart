/// Builds the AudioWorklet module of an app from Dart with
/// tekartik_web_worker_build: compiled with dart2js in
/// `.dart_tool/milomedy_midi_engine/web_worklet/`, built again only when the
/// Dart SDK or a package of the worklet changed, and copied next to the
/// app's page.
library;

import 'dart:io';

import 'package:tekartik_web_worker_build/web_worker_build.dart';

import '../worklet_js.dart';

const _package = 'milomedy_midi_engine';

/// The SoundFont package: its synth is in the worklet when the app depends
/// on it.
const _soundFontPackage = 'milomedy_midi_synth_sf2';

/// The worklet module script.
const _workletScript = WebWorkerScript(
  package: _package,
  filename: midiWorkletDefaultUrl,
  name: 'web_worklet',
  mainSource: _workletMain,
  // The SoundFont synth only when the app depends on it.
  dependencies: [_package, 'milomedy_midi_synth', _soundFontPackage],
  output: _workletModule,
);

String _workletMain(ProjectPackages packages) {
  // The SoundFont synth registered first when the app depends on it.
  var soundFont = packages.has(_soundFontPackage);
  return [
    '// Generated by $_package setup_web_worklet, do not edit.',
    if (soundFont) "import 'package:$_soundFontPackage/midi_synth_sf2.dart';",
    "import 'package:$_package/web_worklet_processor.dart';",
    '',
    'void main() {',
    if (soundFont) '  midiSoundFontRegister();',
    '  midiWorkletMain();',
    '}',
    '',
  ].join('\n');
}

// The dart2js output is the module: the processor registers itself.
String _workletModule(String js, ProjectPackages packages) =>
    midiWorkletModule(js, version: packages.version(_package) ?? 'unknown');

/// What [setupMidiWebWorklet] did.
class MidiWebWorkletSetupResult {
  /// The module written.
  final File file;

  /// The version of milomedy_midi_engine.
  final String version;

  /// True when compiled, false when the cached build was up to date.
  final bool built;

  /// A result.
  MidiWebWorkletSetupResult(this.file, this.version, {required this.built});
}

/// Builds the worklet module of the app at [path] (the current directory by
/// default) when needed, and writes it as [filename] in its [dir] (`web`):
/// the page loads it with `MidiWorkletPlayer.create`. [force] builds again
/// whatever the cache says.
Future<MidiWebWorkletSetupResult> setupMidiWebWorklet({
  String? path,
  String dir = 'web',
  String filename = midiWorkletDefaultUrl,
  bool force = false,
  bool verbose = false,
}) async {
  var result = await _workletScript.setup(
    path: path,
    dir: dir,
    filename: filename,
    force: force,
    verbose: verbose,
  );
  return MidiWebWorkletSetupResult(
    result.file,
    result.version ?? 'unknown',
    built: result.built,
  );
}

/// The main of `bin/setup_web_worklet.dart`.
Future<void> setupMidiWebWorkletMain(List<String> arguments) => _workletScript
    .setupMain(arguments, command: 'dart run $_package:setup_web_worklet');
